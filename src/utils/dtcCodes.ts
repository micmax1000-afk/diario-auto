/**
 * Ritorna la descrizione di un codice DTC: in italiano per la lingua "it",
 * in inglese per tutte le altre lingue.
 */
export function describeDtc(code: string, language = "it"): string | null {
  const key = code.toUpperCase();
  if (language.toLowerCase().startsWith("it")) return DTC_DESCRIPTIONS[key] ?? null;
  return DTC_DESCRIPTIONS_EN[key] ?? DTC_DESCRIPTIONS[key] ?? null;
}
